"""Текстовые признаки сборки — в одном месте (UNIFIED_DESIGN.md, П7, этап E2): метка пункта и код оборудования как
якорь ряда, знаки маркера, отметки бланка, пометка о переносе листа, моноширинный шрифт. Значения перенесены как были."""
import re

# пометка о переносе листа оригинала — служебная строка его разрыва, в переводе её нет (join_tables, lost_segments)
CONT_MARK = re.compile(r"[\s.…_-]*(?:folytat[aá]s\s+a\s+k[öo]vetkez[őo]\s+oldalon|continued\s+on\s+(?:the\s+)?next\s+page)"
                       r"[\s.…_-]*", re.I)
ITEM_LABEL = r"\(?(?:\d+(?:\.\d+)*\.?|[a-zA-Z][.)])\)?"     # номер пункта: «1.», «1.2.», «(3)», «a)»
EQUIP_CODE = r"\d{2}[A-Z]{2}\d{2}[A-Z]\d{3}"                # код оборудования: «31UJ21S601»
ROW_ANCHOR = re.compile(ITEM_LABEL + "|" + EQUIP_CODE)      # якорь ряда таблицы в первом столбце (fullmatch)
MARKERS = "•▪◦·●○■□–\\-"                                    # знаки маркера пункта — для класса регулярки […]
MARK_TICKED = {"○": "◉", "□": "☒", "△": "▲"}                # отметка бланка: пустая → поставленная
MONO_FONT = re.compile(r"(?i)courier|mono|consol")          # моноширинный шрифт — по имени
