"""Геометрия листа для сборки — признаки и пороги в одном месте (UNIFIED_DESIGN.md, П7, этап E2): толщина линии,
двойная линия, полосы колонтитулов, «цветная» заливка, краска на снимке, ширина знака. Значения перенесены как были;
два разных порога одной величины — только под разными именами и с причиной. Факты листа (размеры, фон) — здесь же:
их читают и разметка (docx_struct), и сегменты листа (docx_layout)."""

LINE = 3                # линия, а не рамка или заливка: толщина меньше 3 pt (рамка шапки, линия над подвалом)
DOUBLE = 5              # двойная линия — одна: две параллельные ближе 5 pt (каждая ячейка 1SZ01 обведена в 3,5 pt)
HEAD_EDGE, FOOT_EDGE = 0.14, 0.86   # полоса колонтитула: выше 0,14 / ниже 0,86 высоты листа
FOOT_TEXT = 0.6         # подвал текстового слоя — знаки ниже тела листа и ниже 0,6 его высоты
FOOT_TAGGED = 0.7       # размеченный PDF (низ тела не известен): подвал — строки ниже 0,7 высоты листа…
FOOT_GAP = 15           # …подряд, без разрыва больше 15 pt (или связанные вертикалью штампа)
WHITE, DARK = 0.97, 0.3  # «цветная» заливка (фон ячейки, фон листа): каждый канал темнее WHITE, но светлее DARK —
                         # тёмное «заполнение» — это толстые линии и знаки, а не фон
INK = 200               # краска на снимке листа в оттенках серого — темнее 200 из 255
EDGE_COL = 24           # пустой столбец у края рамки уже 24 pt — вторая линия кромки, а не столбец
SUP_RISE = 0.25         # верхний индекс: знаки подняты над линией строки больше чем на ¼ своего кегля
DIAMOND = 25            # сторона ромба схемы — косой отрезок от 25 pt (у значка «△» и галочки короче)
CHAR_W, CHAR_W_BOLD, CHAR_W_MONO = 0.55, 0.6, 0.6   # средняя ширина знака в долях кегля: Times, полужирный, Courier
CELL_PAD = 12           # поля ячейки LibreOffice (2 × 5,4 pt) с запасом
CELL_PAD_MAX = 14       # поле ячейки оригинала (текст — линия ячейки) больше 14 pt — уже не поле


def hex_rgb(v):
    """Цвет (доли 0…1, RGB) → «RRGGBB»."""
    return "%02X%02X%02X" % tuple(round(255 * c) for c in v[:3])


def tint(fill):
    """«RRGGBB» цветной заливки (не белой и не тёмной) или None — fill: цвет заливки PyMuPDF (get_drawings)."""
    return hex_rgb(fill) if fill and len(fill) >= 3 and DARK < min(fill) < WHITE else None


def page_sizes(path):
    """Размеры листов оригинала (ширина, высота) с учётом поворота (/Rotate): альбомные листы — альбомными разделами
    (docx_build.Builder._page)."""
    import fitz
    with fitz.open(str(path)) as d:
        return [(round(pg.rect.width, 1), round(pg.rect.height, 1)) for pg in d]


def page_bgs(path):
    """Фон листа — заливка во весь лист не белым и не тёмным (жёлтые листы ÜTJ 30HU375GT, 01-02FMP0BIGT): «RRGGBB» или
    None по листам; docx_build кладёт его фоном раздела, все листы которого такого цвета."""
    import fitz
    out = []
    with fitz.open(str(path)) as d:
        for pg in d:
            A = pg.rect.get_area()
            out.append(next((tint(dr["fill"]) for dr in pg.get_drawings()
                             if tint(dr.get("fill")) and fitz.Rect(dr["rect"]).get_area() >= 0.9 * A), None))
    return out
