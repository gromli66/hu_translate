def hex_rgb(v):
    """Цвет (доли 0…1, RGB) → «RRGGBB»."""
    return "%02X%02X%02X" % tuple(round(255 * c) for c in v[:3])


def tint(fill):
    """«RRGGBB» цветной заливки (не белой и не тёмной) или None — fill: цвет заливки PyMuPDF (get_drawings)."""
    return hex_rgb(fill) if fill and len(fill) >= 3 and DARK < min(fill) < WHITE else None


def page_sizes(path):
    """Размеры листов оригинала (ширина, высота) с учётом поворота (/Rotate): альбомные листы — альбомными разделами
    (docx_build.Builder._page)."""
    import fitz
    with fitz.open(str(path)) as d:
        return [(round(pg.rect.width, 1), round(pg.rect.height, 1)) for pg in d]


def page_bgs(path):
    """Фон листа — заливка во весь лист не белым и не тёмным (жёлтые листы ÜTJ 30HU375GT, 01-02FMP0BIGT): «RRGGBB» или
    None по листам; docx_build кладёт его фоном раздела, все листы которого такого цвета."""
    import fitz
    out = []
    with fitz.open(str(path)) as d:
        for pg in d:
            A = pg.rect.get_area()
            out.append(next((tint(dr["fill"]) for dr in pg.get_drawings()
                             if tint(dr.get("fill")) and fitz.Rect(dr["rect"]).get_area() >= 0.9 * A), None))
    return out
